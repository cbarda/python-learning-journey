aktina = float(input("ακτίνα του κύκλου: ")) #ζηταμε απο τον χρηστη να δωσει την ακτινα
PI = 3.14 #me kefalaia orizo tis statheres
perimetros = 2 * PI * aktina #2πR
emvadon = PI * aktina**2 #πR²
print("Η περιμετρος του κυκλου ειναι: " + str(perimetros))
print("Το εμβαδον του κυκλου ειναι: " + str(emvadon))